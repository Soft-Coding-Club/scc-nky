function populateDocument(sceneData, region, point) {
  docTime.textContent = `${formatTime()} 자동 생성 · 클릭 위치 ${Math.round(point.x)}, ${Math.round(point.y)}`;
  docScene.textContent = `${sceneData.episode} · SCENE ${pad(currentSceneIndex + 1)}`;
  issueTitle.textContent = `${region.issue.replace(/\s*논란$/, "")}에 대한 사과문`;
  apologyText.replaceChildren(
    ...apologyParagraphs(sceneData, region, point).map((paragraph) => {
      const element = document.createElement("p");
      element.textContent = paragraph;
      return element;
    }),
  );
  actionNow.textContent = region.immediate;
  actionFuture.textContent = region.prevention;
  printArea.setAttribute("aria-hidden", "false");
}

function renderScene(index) {
  const nextScene = scenes[index];
  sceneImage.classList.add("is-changing");

  window.setTimeout(() => {
    sceneImage.src = nextScene.image;
    sceneImage.alt = nextScene.alt;
    sceneButton.setAttribute("aria-label", `${nextScene.title}. 화면을 클릭해 사과문 PDF를 출력합니다.`);

    const reveal = () => window.requestAnimationFrame(() => sceneImage.classList.remove("is-changing"));
    if (sceneImage.complete) {
      reveal();
    } else {
      sceneImage.addEventListener("load", reveal, { once: true });
    }
  }, 220);
}

function advanceScene(id) {
  if (!interactionLocked || id !== interactionId) return;

  window.clearTimeout(advanceTimer);
  currentSceneIndex = (currentSceneIndex + 1) % scenes.length;
  printArea.setAttribute("aria-hidden", "true");
  renderScene(currentSceneIndex);

  window.setTimeout(() => {
    interactionLocked = false;
    sceneButton.disabled = false;
    sceneButton.focus({ preventScroll: true });
  }, 480);
}

function scheduleAdvance(id, delay = 450) {
  window.clearTimeout(advanceTimer);
  advanceTimer = window.setTimeout(() => advanceScene(id), delay);
}

function accuse(event) {
  if (interactionLocked) return;

  interactionLocked = true;
  sceneButton.disabled = true;
  interactionId += 1;
  const id = interactionId;
  const sceneData = scenes[currentSceneIndex];
  const point = getPoint(event);
  const region = getRegion(point, sceneData.hotspots);

  populateDocument(sceneData, region, point);

  try {
    window.print();
  } finally {
    scheduleAdvance(id, 300);
  }
}

